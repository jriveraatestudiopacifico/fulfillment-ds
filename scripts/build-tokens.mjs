// Turns tokens/tokens.json (DTCG format) into CSS custom properties.
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../tokens/tokens.json', import.meta.url)));
const lines = [];

function walk(node, path) {
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const next = [...path, key];
    if (val && typeof val === 'object' && '$value' in val) {
      const name = `--ds-${next.join('-')}`;
      if (val.$type === 'typography') {
        const { fontWeight, fontSize, lineHeight } = val.$value;
        lines.push(`  ${name}-weight: ${fontWeight};`);
        lines.push(`  ${name}-size: ${fontSize};`);
        lines.push(`  ${name}-line-height: ${lineHeight};`);
      } else {
        lines.push(`  ${name}: ${val.$value};`);
      }
    } else if (val && typeof val === 'object') {
      walk(val, next);
    }
  }
}

walk(tokens, []);
const css = `/* Generated by scripts/build-tokens.mjs. Do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n`;
writeFileSync(new URL('../tokens/tokens.css', import.meta.url), css);
console.log(`tokens.css: ${lines.length} variables`);
